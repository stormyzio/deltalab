export function getTargetBondLength(a: string, b: string, order: 1 | 2 | 3): number {
  const pair = a <= b ? `${a}-${b}:${order}` : `${b}-${a}:${order}`
  const exact = BOND_LENGTH_TABLE[pair]
  if (exact !== undefined) return exact
  const base = getCovalentRadius(a) + getCovalentRadius(b)
  const reduction = order === 1 ? 0 : order === 2 ? 0.19 : 0.33
  return Math.max(0.72, base - reduction)
}
